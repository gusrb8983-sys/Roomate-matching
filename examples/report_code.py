# ===== 코드 1. 사용자와 매물 데이터 표현 (딕셔너리, 리스트, 튜플) =====
u007 = {"id": "u007", "성별": "M", "희망성별": "M",
        "희망지역": ["명륜동1가", "명륜동2가"],
        "보증금": (500, 1000), "월세": (40, 50), "거주기간": 12,
        "흡연": False, "흡연허용": False, "반려동물": False, "반려동물허용": True,
        "생활패턴": [3, 3, 3, 3]}      # [생활 시간대, 청결, 소음, 교류]
u017 = {"id": "u017", "성별": "M", "희망성별": "M",
        "희망지역": ["삼선동1가", "명륜동1가"],
        "보증금": (500, 1000), "월세": (40, 50), "거주기간": 12,
        "흡연": False, "흡연허용": False, "반려동물": False, "반려동물허용": False,
        "생활패턴": [1, 3, 2, 3]}
p004 = {"id": "P004", "법정동": "명륜동1가", "보증금": 1000, "월세": 90}

인당보증금 = p004["보증금"] / 2
인당월세 = p004["월세"] / 2
print(f"{p004['id']} 1인 부담: 보증금 {인당보증금:.0f}만 원, 월세 {인당월세:.0f}만 원")


# ===== 코드 2. 제외 조건 판정 (중첩 if문, 논리·멤버십 연산자) =====
a, b = u007, u017
결과 = "통과"

if a["희망성별"] != b["성별"] or b["희망성별"] != a["성별"]:
    결과 = "제외: 성별"
elif (a["흡연"] and not b["흡연허용"]) or (b["흡연"] and not a["흡연허용"]):
    결과 = "제외: 흡연"
elif (a["반려동물"] and not b["반려동물허용"]) or (b["반려동물"] and not a["반려동물허용"]):
    결과 = "제외: 반려동물"
else:
    if p004["법정동"] not in a["희망지역"] or p004["법정동"] not in b["희망지역"]:
        결과 = "제외: 희망 지역"
    else:
        a예산 = a["보증금"][0] <= 인당보증금 <= a["보증금"][1] and a["월세"][0] <= 인당월세 <= a["월세"][1]
        b예산 = b["보증금"][0] <= 인당보증금 <= b["보증금"][1] and b["월세"][0] <= 인당월세 <= b["월세"][1]
        if not (a예산 and b예산):
            결과 = "제외: 예산"
        elif abs(a["거주기간"] - b["거주기간"]) > 12:
            결과 = "제외: 거주 기간"

print(f"{a['id']} - {b['id']} 판정 결과: {결과}")


# ===== 코드 3. 일치율 계산 (산술 연산, 인덱싱, if-else) =====
pa, pb = a["생활패턴"], b["생활패턴"]

# 항목별 유사도: 1 - |차이| / 4
s = [1 - abs(pa[0] - pb[0]) / 4, 1 - abs(pa[1] - pb[1]) / 4,
     1 - abs(pa[2] - pb[2]) / 4, 1 - abs(pa[3] - pb[3]) / 4]

# 중요도: 생활 시간대·교류는 1 + 2×|값-3|, 청결·소음은 6 - 값
wa = [1 + 2 * abs(pa[0] - 3), 6 - pa[1], 6 - pa[2], 1 + 2 * abs(pa[3] - 3)]
wb = [1 + 2 * abs(pb[0] - 3), 6 - pb[1], 6 - pb[2], 1 + 2 * abs(pb[3] - 3)]

a점수 = (wa[0]*s[0] + wa[1]*s[1] + wa[2]*s[2] + wa[3]*s[3]) / (wa[0] + wa[1] + wa[2] + wa[3])
b점수 = (wb[0]*s[0] + wb[1]*s[1] + wb[2]*s[2] + wb[3]*s[3]) / (wb[0] + wb[1] + wb[2] + wb[3])
일치율 = 100 * (a점수 * b점수) ** 0.5

print(f"{a['id']} 입장 {a점수:.3f}, {b['id']} 입장 {b점수:.3f}")
if 일치율 >= 60:
    print(f"일치율 {round(일치율, 1)}점 → 추천 목록에 포함")
else:
    print(f"일치율 {round(일치율, 1)}점 → 60점 미만이라 추천에서 제외")
